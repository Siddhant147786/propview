const router = require("express").Router();
const controller = require("../controllers/propertyController");
const { requireAuth } = require("../middleware/auth");
const { receiveImages } = require("../middleware/uploads");
const { requireCloudinary } = require("../services/cloudinaryService");
router.get("/", controller.list);
router.get("/neighbourhoods", controller.neighbourhoods);
router.get("/mine", requireAuth, controller.mine);
router.get("/:id/edit", requireAuth, controller.loadOwned, controller.editData);
router.get("/:id", controller.detail);
router.post("/", requireAuth, requireCloudinary, receiveImages, controller.create);
router.patch("/:id", requireAuth, controller.loadOwned, receiveImages, controller.update);
router.delete("/:id", requireAuth, controller.loadOwned, controller.remove);
module.exports = router;
